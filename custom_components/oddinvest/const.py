# CONF_TOKEN — Bearer для REST, коли на сервісі стоїть замок. Береться в
# самому застосунку: «Налаштування → Доступ ззовні → Видати токен».
# Порожньо = сервіс без пароля (перший запуск).
#
# Публічної адреси тут НЕМАЄ навмисно: її задає сам сервіс при підключенні
# тунелю й публікує в документі стану (settings.public_url), звідки її бере
# OddInvestData.open_url. Поле інтеграції для тієї самої адреси було б
# другим джерелом однієї правди — і застаріло б рівно тоді, коли адресу
# міняли. REST при цьому й далі ходить на base_url у локальній мережі: за
# зовнішньою адресою може стояти другий замок (Cloudflare Access), якого
# машина не пройде.
CONF_TOKEN = "token"

# CONF_PORTFOLIO — slug портфеля, коли запис дивиться НЕ на головний
# (MQTT-префікс «<prefix>/<slug>»). Порожньо = головний: так поводились усі
# записи доти, і міграції не треба — читається через entry.data.get(...).
# Сервіс розрізняє портфелі заголовком X-Portfolio (actions.rest_headers); без нього дії
# («Отримано», «Оновити») з запису другого портфеля міняли б головний.
